import React from "react"

interface PrintLayoutProps {
  children: React.ReactNode
  title: string
  showHeader?: boolean
  companyName?: string
  companyLogo?: string
  companyAddress?: string
  companyPhone?: string
  companyEmail?: string
  reference?: string
  date?: Date
  referenceLabel?: string
  dateLabel?: string
  footerText?: string
  dateLocale?: string
}

export function PrintLayout({
  children,
  title,
  showHeader = true,
  companyName,
  companyLogo,
  companyAddress,
  companyPhone,
  companyEmail,
  reference,
  date,
  referenceLabel = "Ref",
  dateLabel = "Date",
  footerText,
  dateLocale = "fr-FR",
}: PrintLayoutProps) {
  return (
    <div className="print-layout min-h-screen bg-white text-gray-950">
      {showHeader && (
        <div className="print-header mb-8 border-b-2 border-gray-800 pb-6">
          <div className="flex items-start justify-between">
            <div className="space-y-2">
              {companyLogo && <img src={companyLogo} alt="Company Logo" className="mb-2 h-12 w-auto" />}
              {companyName && (
                <>
                  <h1 className="text-2xl font-bold text-gray-900">{companyName}</h1>
                  {companyAddress && <p className="text-sm text-gray-600">{companyAddress}</p>}
                  {companyPhone && <p className="text-sm text-gray-600">Tel: {companyPhone}</p>}
                  {companyEmail && <p className="text-sm text-gray-600">Email: {companyEmail}</p>}
                </>
              )}
            </div>

            <div className="space-y-1 text-right">
              <h2 className="text-xl font-bold uppercase text-gray-900">{title}</h2>
              {reference && (
                <p className="text-sm font-semibold">
                  {referenceLabel}: <span className="font-mono">{reference}</span>
                </p>
              )}
              {date && (
                <p className="text-sm text-gray-600">
                  {dateLabel}:{" "}
                  {date.toLocaleDateString(dateLocale, {
                    day: "numeric",
                    month: "long",
                    year: "numeric",
                  })}
                </p>
              )}
            </div>
          </div>
        </div>
      )}

      <div className="print-content">{children}</div>

      <div className="print-footer mt-8 border-t border-gray-300 pt-6 text-center text-sm text-gray-500">
        <p>
          {footerText ||
            `Generated by BuildStock Pro on ${new Date().toLocaleDateString("fr-FR", {
              day: "numeric",
              month: "long",
              year: "numeric",
              hour: "2-digit",
              minute: "2-digit",
            })}`}
        </p>
      </div>

      <style jsx>{`
        .print-layout {
          max-width: 210mm;
          margin: 0 auto;
          padding: 24px;
        }

        @media print {
          .print-layout {
            background: white !important;
            min-height: auto !important;
            max-width: none !important;
            width: 100% !important;
            margin: 0 !important;
            padding: 12mm 14mm !important;
            box-shadow: none !important;
          }

          .print-header {
            page-break-after: avoid;
          }

          .print-content {
            break-inside: auto;
          }

          .print-footer {
            break-before: avoid;
          }

          * {
            box-shadow: none !important;
            text-shadow: none !important;
            color: #000 !important;
          }

          h1,
          h2,
          h3,
          h4,
          h5,
          h6 {
            page-break-after: avoid;
          }

          table {
            page-break-inside: avoid;
          }

          img {
            max-width: 100% !important;
          }

          thead {
            display: table-header-group;
          }

          tfoot {
            display: table-footer-group;
          }

          tr {
            page-break-inside: avoid;
          }
        }
      `}</style>
    </div>
  )
}
